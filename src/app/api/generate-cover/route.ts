import { NextResponse } from "next/server";
import { GoogleGenAI } from "@google/genai";

export async function POST(req: Request) {
    try {
        const { idea } = await req.json();

        if (!process.env.GEMINI_API_KEY) {
            return NextResponse.json(
                { error: "Gemini API key not configured" },
                { status: 500 }
            );
        }

        const ai = new GoogleGenAI({ apiKey: process.env.GEMINI_API_KEY });

        const prompt = `Create a stunning, highly detailed album cover art based on this song concept: "${idea || 'A beautiful, abstract musical landscape'}". Make it aesthetic, vivid, and fitting for a premium music release. Square aspect ratio, highly artistic, no text or words on the image.`;

        const response = await ai.models.generateImages({
            model: 'imagen-4.0-generate-001',
            prompt: prompt,
            config: {
                numberOfImages: 1,
                aspectRatio: '1:1',
                outputMimeType: 'image/jpeg'
            }
        });

        if (response.generatedImages && response.generatedImages.length > 0) {
            const base64Image = response.generatedImages[0].image?.imageBytes;
            if (!base64Image) throw new Error("Image bytes missing from Gemini response.");
            return NextResponse.json({ imageBase64: base64Image });
        } else {
            throw new Error("No image generated by Gemini.");
        }

    } catch (error: any) {
        console.error("Error generating cover art:", error);
        return NextResponse.json(
            { error: error.message || "Failed to generate cover art" },
            { status: 500 }
        );
    }
}
